#!/usr/bin/env python3
"""Builds assets/lucide-subset.ttf from the unpacked npm package lucide-static (ISC licence).

Usage (from the repo root):
    npm pack lucide-static@<version>      # in an empty folder, then unpack with tar
    python tools/make_icon_font.py <path to the unpacked "package" folder>

Writes assets/lucide-subset.ttf, third_party/lucide/LICENSE and updates the generated block
(HZ_ICON_* codepoints) in include/horizon_imgui.h and the codepoint array in src/host/ui/ui_icons.h.
Codepoints are Lucide's own and are plugin ABI: never renumber, only append icons.
Needs fontTools (python -m pip install --user fonttools).
"""
import json
import os
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ICONS = [
    "settings", "keyboard", "scroll-text", "info", "puzzle", "layout-grid", "square-arrow-out-up-right",
    "external-link", "picture-in-picture-2", "pin", "pin-off", "lock", "lock-open", "eye", "eye-off",
    "mouse-pointer-click", "x", "minus", "plus", "check", "chevron-down", "chevron-up", "chevron-left",
    "chevron-right", "upload", "cloud-upload", "refresh-cw", "save", "play", "film", "camera", "timer",
    "map", "flag", "trophy", "power", "folder-open", "link", "unlink", "wifi", "wifi-off", "circle-alert",
    "triangle-alert", "sliders-horizontal", "search", "trash-2", "copy", "download", "layers",
    "grip-vertical", "monitor", "house", "menu",
]

BEGIN = "// BEGIN HZ_ICONS (generated by tools/make_icon_font.py, do not edit)"
END = "// END HZ_ICONS"


def u8(cp):
    return "".join("\\x%02x" % b for b in chr(cp).encode("utf-8"))


def macro(name):
    return "HZ_ICON_" + name.upper().replace("-", "_")


def replace_block(path, block, tail_if_missing=True):
    with open(path, "r", newline="") as f:
        text = f.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    block = block.replace("\n", nl)
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip() + nl + nl + block + nl
    with open(path, "w", newline="") as f:
        f.write(text)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    pkg = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(pkg, "font", "codepoints.json"), encoding="utf-8") as f:
        cps = json.load(f)
    missing = [n for n in ICONS if n not in cps]
    if missing:
        print("not in this Lucide version:", ", ".join(missing))
        return 1
    codes = [cps[n] for n in ICONS]

    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [1, 2, 3, 4, 6]
    opts.glyph_names = False
    font = TTFont(os.path.join(pkg, "font", "lucide.ttf"))
    ss = subset.Subsetter(opts)
    ss.populate(unicodes=codes)
    ss.subset(font)
    out = os.path.join(root, "assets", "lucide-subset.ttf")
    font.save(out)
    print("wrote", out, os.path.getsize(out), "bytes,", len(ICONS), "icons")

    lic = os.path.join(root, "third_party", "lucide")
    os.makedirs(lic, exist_ok=True)
    shutil.copyfile(os.path.join(pkg, "LICENSE"), os.path.join(lic, "LICENSE"))

    lines = [BEGIN,
             "// Icons: Lucide (ISC licence), a subset merged into every host font (body, bold, title, small, mono).",
             "// Draw them with any host font, e.g. ImGui::Text(HZ_ICON_SETTINGS_U8 \" Settings\").",
             "// The codepoints are Lucide's own and plugin ABI: they never change, new icons are only added.",
             "// HZ_ICON_<NAME> is the codepoint (Private Use Area), HZ_ICON_<NAME>_U8 the same as a UTF-8 string."]
    for n, c in zip(ICONS, codes):
        lines.append("#define %s 0x%04Xu" % (macro(n), c))
        lines.append("#define %s_U8 \"%s\"" % (macro(n), u8(c)))
    lines.append(END)
    replace_block(os.path.join(root, "include", "horizon_imgui.h"), "\n".join(lines))

    arr = ["// Generated by tools/make_icon_font.py: glyph ranges of the icon font (pairs, 0-terminated).",
           "#pragma once", "", "static const unsigned short kIconRanges[] = {"]
    for c in sorted(codes):
        arr.append("    0x%04X, 0x%04X," % (c, c))
    arr += ["    0};", ""]
    with open(os.path.join(root, "src", "host", "ui", "ui_icons.h"), "w", newline="") as f:
        f.write("\r\n".join(arr))
    print("updated include/horizon_imgui.h and src/host/ui/ui_icons.h")
    for n, c in zip(ICONS, codes):
        print("%-30s 0x%04X" % (macro(n), c))
    return 0


if __name__ == "__main__":
    sys.exit(main())
