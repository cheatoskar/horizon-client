void Binder::logf(int level, const char* fmt, ...) {
    if (!log_) return;
    char buf[600];
    va_list ap;
    va_start(ap, fmt);
    _vsnprintf_s(buf, sizeof(buf), _TRUNCATE, fmt, ap);
    va_end(ap);
    log_(logUser_, level, buf);
}

bool Binder::verify() {
    if (verified_) return true;
    if (failed_ || !t_) return false;
    for (int i = 0; i < t_->codeCount; i++) {
        const CodeSig& s = t_->code[i];
        uint8_t buf[64];
        if (s.len > sizeof(buf) || !safeRead(reinterpret_cast<const void*>(rb(s.addr)), buf, s.len) || memcmp(buf, s.bytes, s.len) != 0) {
            failed_ = true;
            logf(1, "bindings code at %08X is not as expected: a late pad gets no bindings (set it up in the game's input settings)",
                 static_cast<unsigned>(s.addr));
            return false;
        }
    }
    verified_ = true;
    logf(0, "bindings code checked (%d code signatures)", t_->codeCount);
    return true;
}

void Binder::apply(uint8_t* port, uint32_t devIndex, const std::wstring& name) {
    last_ = Result();
    const std::string nm = toUtf8(name);
    if (!verify()) return;
    const uintptr_t p = reinterpret_cast<uintptr_t>(port);
    uintptr_t app = 0, cb = 0, appPort = 0;
    if (!rd(rb(t_->appGlobal), app) || !app) {
        logf(1, "bindings for %s: no game app yet; set the pad up in the game's input settings", nm.c_str());
        return;
    }
    if (!rd(app + t_->appDefaultsCb, cb) || cb != rb(t_->setDefaults) || !rd(app + t_->appPort, appPort) || appPort != p) {
        logf(1, "bindings for %s: the app %08X is not as expected (defaults %08X, port %08X): nothing changed", nm.c_str(),
             static_cast<unsigned>(app), static_cast<unsigned>(cb), static_cast<unsigned>(appPort));
        return;
    }
    uint32_t devCount = 0;
    uintptr_t devArr = 0, dev = 0, devVt = 0, objFn = 0;
    uint32_t id = 0;
    if (!rd(p + kPortDevCount, devCount) || devIndex >= devCount || !rd(p + kPortDevArray, devArr) || !rd(devArr + devIndex * 4, dev) ||
        !dev || !rd(dev + kDevId, id) || !rd(dev, devVt) || !rd(devVt + kPadObjectSlot, objFn) || !objFn) {
        logf(1, "bindings for %s: device %u not readable: nothing changed", nm.c_str(), devIndex);
        return;
    }
    uintptr_t config = 0, cfgPort = 0;
    if (!callCurConfig(rb(t_->currentConfig), app, &config) || !config || !rd(config + kCfgPort, cfgPort) || cfgPort != p) {
        logf(1, "bindings for %s: no bindings config of the current profile (%08X): nothing changed", nm.c_str(),
             static_cast<unsigned>(config));
        return;
    }
    Scan before = {}, after = {};
    if (!scanConfig(config, id, &before)) {
        logf(2, "bindings for %s: the bindings config %08X could not be read: nothing changed", nm.c_str(), static_cast<unsigned>(config));
        return;
    }
    if (!before.known) {
        // the game's own pass: defaults for every device the config has no binding for (only the new pad now)
        if (!callPass(rb(t_->defaultsPass), app, config)) {
            logf(2, "bindings for %s: the game's default bindings crashed", nm.c_str());
            return;
        }
        if (!scanConfig(config, id, &after)) return;
    } else {
        after = before;
    }
    last_.saved = before.known != 0;
    last_.configPairs = after.count;
    std::string list;
    for (int i = 0; i < after.count; i++) {
        // name by the game's action list (log only): the config's action index is the position in that list
        uintptr_t listed = 0;
        const int pos = after.actionIdx[i];
        std::string an = rd(rb(t_->actionList) + static_cast<uintptr_t>(pos) * 4, listed) && listed == after.pairs[i].action
                             ? actionName(pos)
                             : "action " + std::to_string(pos);
        char ob[16];
        sprintf_s(ob, "%X", after.pairs[i].object);
        if (!list.empty()) list += ", ";
        list += an + "=" + ob;
    }
    logf(0, "bindings for %s (id %08X): %s, %d binding(s): %s", nm.c_str(), id,
         before.known ? "saved in the profile, kept" : "the game's defaults added to the profile", after.count,
         list.empty() ? "none" : list.c_str());

    // tables of the port
    uint32_t tables = 0;
    uintptr_t tableArr = 0;
    if (!rd(p + kPortTableCount, tables) || !rd(p + kPortTableArray, tableArr) || tables > 256) return;
    auto owned = [&](uintptr_t tbl) {
        for (uint32_t i = 0; i < tables; i++) {
            uintptr_t x = 0;
            if (rd(tableArr + i * 4, x) && x == tbl) return true;
        }
        return false;
    };
    // the running race's table: the pad's bindings, now (otherwise only from the next race start)
    uintptr_t race = 0, rApp = 0, rPort = 0, rTable = 0, vt = 0;
    if (rd(app + t_->appRace, race) && race && rd(race + t_->raceApp, rApp) && rApp == app && rd(race + t_->racePort, rPort) &&
        rPort == p && rd(race + t_->raceConfigTable, rTable) && rTable && owned(rTable) && rd(rTable, vt) && vt == rb(t_->configTableVtbl)) {
        const char* why = "";
        if (appendToTable(reinterpret_cast<uint8_t*>(rTable), devIndex, after.pairs, after.count, reserve8_, &why))
            last_.raceAdded = after.count;
        else
            logf(1, "bindings for %s: race table not changed (%s); they apply from the next race start", nm.c_str(), why);
    }
    // "all objects" tables (menus and the race's pause menu): the pad entries the game's builder adds per pad
    BindPair menu[10];
    int menuN = 0;
    for (const auto& e : kAllPad) {
        uint32_t obj = 0xffffffffu;
        uintptr_t action = 0;
        if (!callPadObject(objFn, dev, e.kind, e.index, &obj) || obj == 0xffffffffu) continue;
        if (!rd(rb(t_->allActions[e.slot]), action) || !action) continue;
        menu[menuN++] = BindPair{static_cast<uint32_t>(action), obj};
    }
    for (uint32_t i = 0; i < tables && menuN > 0; i++) {
        uintptr_t tbl = 0;
        if (!rd(tableArr + i * 4, tbl) || !tbl || !rd(tbl, vt) || vt != rb(t_->allTableVtbl)) continue;
        const char* why = "";
        if (appendToTable(reinterpret_cast<uint8_t*>(tbl), devIndex, menu, menuN, reserve8_, &why)) {
            last_.menuAdded += menuN;
            last_.menuTables++;
        } else {
            logf(1, "bindings for %s: menu table %08X not changed (%s)", nm.c_str(), static_cast<unsigned>(tbl), why);
        }
    }
    last_.ok = true;
    logf(0, "bindings for %s: race table %s, %d menu binding(s) in %d table(s)", nm.c_str(),
         last_.raceAdded ? ("+" + std::to_string(last_.raceAdded)).c_str() : (race ? "unchanged" : "none (not in a race)"),
         last_.menuAdded, last_.menuTables);
}

