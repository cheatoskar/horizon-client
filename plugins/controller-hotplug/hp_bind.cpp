bool safeRead(const void* p, void* out, size_t n) {
    __try {
        memcpy(out, p, n);
        return true;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return false;
    }
}
template <typename T> bool rd(uintptr_t addr, T& out) { return safeRead(reinterpret_cast<const void*>(addr), &out, sizeof(T)); }

using CurCfgFn = uintptr_t(__fastcall*)(uintptr_t app, void* edx);              // thiscall, no args
using PassFn = void(__fastcall*)(uintptr_t app, void* edx, uintptr_t config);   // thiscall, ret 4
using PadObjFn = uint32_t(__fastcall*)(uintptr_t dev, void* edx, uint32_t kind, uint32_t index); // ret 8
using ReserveFn = void(__fastcall*)(void* array, void* edx, uint32_t n);         // thiscall, ret 4

int callCurConfig(uintptr_t fn, uintptr_t app, uintptr_t* out) {
    __try {
        *out = reinterpret_cast<CurCfgFn>(fn)(app, nullptr);
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return 0;
    }
}
int callPass(uintptr_t fn, uintptr_t app, uintptr_t config) {
    __try {
        reinterpret_cast<PassFn>(fn)(app, nullptr, config);
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return 0;
    }
}
int callPadObject(uintptr_t fn, uintptr_t dev, uint32_t kind, uint32_t index, uint32_t* out) {
    __try {
        *out = reinterpret_cast<PadObjFn>(fn)(dev, nullptr, kind, index);
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return 0;
    }
}

struct Scan {
    int known;      // the config lists the device id (it has bindings for it)
    int count;      // entries for the device
    int actionIdx[kMaxPairs];
    BindPair pairs[kMaxPairs];
};
int scanConfig(uintptr_t config, uint32_t id, Scan* s) {
    __try {
        s->known = 0;
        s->count = 0;
        const uint32_t ids = *reinterpret_cast<uint32_t*>(config + kCfgIdCount);
        const uint32_t* idList = *reinterpret_cast<uint32_t**>(config + kCfgIds);
        if (ids > 4096) return 0;
        for (uint32_t i = 0; i < ids; i++)
            if (idList[i] == id) s->known = 1;
        const uint32_t n = *reinterpret_cast<uint32_t*>(config + kCfgEntryCount);
        const uint32_t* e = *reinterpret_cast<uint32_t**>(config + kCfgEntries);
        const uint32_t actions = *reinterpret_cast<uint32_t*>(config + kCfgActionCount);
        const uint32_t* act = *reinterpret_cast<uint32_t**>(config + kCfgActions);
        if (n > 65536 || actions > 4096) return 0;
        for (uint32_t i = 0; i < n; i++) {
            const uint32_t* x = e + i * 3; // {action index, device id, object}
            if (x[1] != id || x[0] >= actions || x[2] == 0xffffffffu) continue;
            if (s->count >= kMaxPairs) break;
            s->actionIdx[s->count] = static_cast<int>(x[0]);
            s->pairs[s->count].action = act[x[0]];
            s->pairs[s->count].object = x[2];
            s->count++;
        }
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return 0;
    }
}

int appendRaw(uint8_t* table, uint32_t devIndex, const BindPair* pairs, int n, uintptr_t reserve8, const char** why) {
    __try {
        const uint32_t rc = *reinterpret_cast<uint32_t*>(table + kTblRangeCount);
        uint32_t* ranges = *reinterpret_cast<uint32_t**>(table + kTblRanges);
        uint32_t* bindArr = reinterpret_cast<uint32_t*>(table + kTblBindCount); // {count, ptr, cap}
        const uint32_t bc = bindArr[0];
        if (rc != devIndex + 1 || !ranges) {
            *why = "the pad is not the table's last device";
            return 0;
        }
        if (ranges[devIndex * 2 + 1] != 0) {
            *why = "the table has bindings for the pad already";
            return 0;
        }
        if (ranges[devIndex * 2] != bc) {
            *why = "the pad's range is not at the end of the table";
            return 0;
        }
        if (n <= 0) return 1;
        reinterpret_cast<ReserveFn>(reserve8)(bindArr, nullptr, bc + static_cast<uint32_t>(n));
        uint32_t* items = reinterpret_cast<uint32_t*>(static_cast<uintptr_t>(bindArr[1]));
        for (int i = 0; i < n; i++) {
            items[(bc + i) * 2] = pairs[i].action;
            items[(bc + i) * 2 + 1] = pairs[i].object;
        }
        bindArr[0] = bc + static_cast<uint32_t>(n);
        ranges[devIndex * 2 + 1] = static_cast<uint32_t>(n);
        // the lookup cursor points into the bindings (which may have moved): back to its start state
        *reinterpret_cast<uint32_t*>(table + kTblCursorDev) = 0;
        *reinterpret_cast<uint32_t*>(table + kTblCursorFlag) = 0xffffffffu;
        *reinterpret_cast<uint32_t*>(table + kTblCursorPtr) = bindArr[1];
        return 1;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        *why = "access fault";
        return 0;
    }
}

